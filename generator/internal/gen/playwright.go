package gen

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"sightkick/generator/playwrightbundle"
)

// EmitPlaywright emits a self-contained ES module and its NodeNext declaration
// file. The original IR is unchanged; only this consumer adds executable code.
func EmitPlaywright(ir IR) (string, string, error) {
	for _, tool := range ir.Tools {
		if tool.Mode != "live" {
			return "", "", fmt.Errorf("Playwright: tool %q has unsupported mode %q", tool.Name, tool.Mode)
		}
	}
	data, err := json.Marshal(ir)
	if err != nil {
		return "", "", err
	}
	js := "// Generated by sightkick. Do not edit.\n" + playwrightbundle.JS + "\nconst ir = JSON.parse(" + quote(string(data)) + ");\nexport function createSightkick(page, options) { return bindSightkick(page, ir, options); }\n"
	var d strings.Builder
	d.WriteString(`// Generated by sightkick. Do not edit.
import type { Page } from "playwright";
export interface Options { timeoutMs?: number; log?: (message: string) => void }
export interface ToolResult { ok: boolean; message?: string; skipped?: boolean; guidance?: { tool: string; reason?: string; when: "now" | "after_navigation"; view?: string }[] }
export interface Sightkick {
  tools: {
`)
	for _, tool := range ir.Tools {
		d.WriteString("    " + quote(tool.Name) + ": (params")
		if len(tool.InputSchema.Required) == 0 {
			d.WriteString("?")
		}
		d.WriteString(": { ")
		required := map[string]bool{}
		for _, key := range tool.InputSchema.Required {
			required[key] = true
		}
		keys := make([]string, 0, len(tool.InputSchema.Properties))
		for key := range tool.InputSchema.Properties {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		for _, key := range keys {
			prop := tool.InputSchema.Properties[key]
			d.WriteString(quote(key))
			if !required[key] {
				d.WriteString("?")
			}
			d.WriteString(": ")
			if len(prop.Enum) > 0 {
				for i, value := range prop.Enum {
					if i > 0 {
						d.WriteString(" | ")
					}
					d.WriteString(quote(value))
				}
			} else {
				switch prop.Type {
				case "string", "boolean", "number":
					d.WriteString(prop.Type)
				default:
					d.WriteString("unknown")
				}
			}
			d.WriteString("; ")
		}
		d.WriteString("}) => Promise<ToolResult")
		if tool.Returns != nil {
			if tool.Returns.Kind == "list" {
				d.WriteString(" & { items?: { ")
				fields := make([]string, 0, len(tool.Returns.Fields))
				for key := range tool.Returns.Fields {
					fields = append(fields, key)
				}
				sort.Strings(fields)
				for _, key := range fields {
					d.WriteString(quote(key) + ": string; ")
				}
				d.WriteString("}[] }")
			} else if tool.Returns.Query != nil && tool.Returns.Extractor != nil {
				d.WriteString(" & { value?: string }")
			}
		}
		d.WriteString(">;\n")
	}
	d.WriteString("  };\n  views: {\n")
	for _, view := range ir.Views {
		d.WriteString("    " + quote(view.Name) + ": { waitFor(options?: { timeoutMs?: number }): Promise<void> };\n")
	}
	d.WriteString("  };\n}\nexport declare function createSightkick(page: Page, options?: Options): Sightkick;\n")
	return js, d.String(), nil
}

func quote(s string) string { b, _ := json.Marshal(s); return string(b) }
